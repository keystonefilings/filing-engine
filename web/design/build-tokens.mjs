// Builds CoFile's token outputs from web/design/tokens.json (merged spec 13.2):
//   web/styles/tokens.css     palette (light, dark, data-theme), fonts, space, corners, depth, motion
//   web/styles/type.css       one class per type role (.t-<role>), fluid between 390 and 1440 px
//   web/lib/design/tokens.ts  the same values as constants, for the proof renderer, emails and canvas work
// Run with `npm run tokens`. `npm run tokens -- --check` fails if the outputs are out of date.
import { readFileSync, writeFileSync, existsSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";

const here = dirname(fileURLToPath(import.meta.url));
const web = join(here, "..");
const t = JSON.parse(readFileSync(join(here, "tokens.json"), "utf8"));
const drop$ = (o) => Object.fromEntries(Object.entries(o).filter(([k]) => !k.startsWith("$")));

const PHONE = 390, DESKTOP = 1440;
const rem = (px) => `${+(px / 16).toFixed(4)}rem`;
/** clamp() that is `phone` px at a 390 px viewport and `desktop` px at 1440, in rem so it follows text size. */
function fluid(phone, desktop) {
  if (phone === desktop) return rem(phone);
  const slope = (desktop - phone) / (DESKTOP - PHONE);
  const base = phone - slope * PHONE;
  const lo = Math.min(phone, desktop), hi = Math.max(phone, desktop);
  return `clamp(${rem(lo)}, ${rem(base)} + ${+(slope * 100).toFixed(4)}vw, ${rem(hi)})`;
}

const header = "/* Generated by web/design/build-tokens.mjs from web/design/tokens.json. Don't edit: change tokens.json and run `npm run tokens`. */\n";
const vars = (o, prefix = "") => Object.entries(drop$(o)).map(([k, v]) => `  --${prefix}${k}: ${v};`).join("\n");

// ---- tokens.css ----
const light = drop$(t.color.light), dark = drop$(t.color.dark), firm = drop$(t.color.firmExample);
const fontVars = Object.entries(t.font).map(([k, v]) => `  --font-${k}: ${v};`).join("\n");
const spaceVars = t.space.map((s) => `  --s-${s}: ${s}px;`).join("\n");
const radiusVars = Object.entries(t.radius).map(([k, v]) => `  --r-${k}: ${v};`).join("\n");
const elevVars = Object.entries(t.elevation).map(([k, v]) => `  --e-${k}: ${v};`).join("\n");
const easeVars = Object.entries(t.motion.ease).map(([k, v]) => `  --ease-${k}: ${v};`).join("\n");
const durVars = Object.entries(t.motion.duration).map(([k, v]) => `  --t-${k}: ${v}ms;`).join("\n");
const layoutVars = [
  `  --content-max: ${t.layout["content-max"]}px;`,
  `  --measure-body: ${t.layout["measure-body"]};`,
  `  --measure-long: ${t.layout["measure-long"]};`,
  `  --form-max: ${t.layout["form-max"]}px;`,
  `  --sheet-max: ${t.layout["sheet-max"]}px;`,
].join("\n");

const tokensCss = `${header}
/* Layer order for every new stylesheet. Legacy styles (globals.css, landing.css) are unlayered for now and
   only reach pages not yet rebuilt; new styles apply inside a register (.reg-cofile, .reg-firm, .reg-white). */
@layer legacy, tokens, base, components, pictures, utilities;

@layer tokens {
:root {
  /* CoFile's palette, light (4.2-4.3) */
${vars(light)}
  /* The example firm, Harbor & Pine CPA (4.7); real firm pages set these from the ink match */
${vars(firm)}
  /* Faces (5.1): licensed families first, then the stand-ins until the licenses are bought */
${fontVars}
  /* Space (6.3), corners and depth (6.4), layout (6.2) */
${spaceVars}
${radiusVars}
${elevVars}
${layoutVars}
  /* Motion (D2) */
${easeVars}
${durVars}
}

/* Dark mode: night stock (4.6). Sheets keep their light inks (registers.css, .sheet). */
@media (prefers-color-scheme: dark) {
  :root:not([data-theme="light"]) {
${vars(dark).replace(/^ {2}/gm, "    ")}
  }
}
:root[data-theme="dark"] {
${vars(dark)}
}

@media (prefers-reduced-motion: reduce) {
  :root { --t-quick: 0ms; --t-press: 0ms; --t-ink: 0ms; --t-set: 0ms; --t-draw: 0ms; --t-light: 0ms; }
}
}
`;

// ---- type.css ----
const faceVar = (face) => (face === "firm" ? "var(--font-firm, var(--font-sans-display))" : `var(--font-${face})`);
const roles = drop$(t.type);
const typeCss = `${header}
/* One class per type role (5.2, 5.3). Sizes are fluid between a 390 px and a 1440 px viewport. */
@layer base {
${Object.entries(roles).map(([name, r]) => {
  const lines = [
    `font-family: ${faceVar(r.face)}`,
    `font-size: ${fluid(r.phone[0], r.desktop[0])}`,
    `line-height: ${fluid(r.phone[1], r.desktop[1])}`,
    `font-weight: ${r.weight}`,
  ];
  if (r.tracking) lines.push(`letter-spacing: ${+(r.tracking / 100).toFixed(4)}em`);
  if (r.italic) lines.push("font-style: italic");
  if (r.numeric) lines.push(`font-variant-numeric: ${r.numeric}`);
  if (r.color) lines.push(`color: var(--text-2, var(--${r.color}))`);
  return `.t-${name} { ${lines.join("; ")}; }`;
}).join("\n")}
}
`;

// ---- tokens.ts ----
const tokensTs = `// Generated by web/design/build-tokens.mjs from web/design/tokens.json. Don't edit: change tokens.json and run \`npm run tokens\`.
export const color = ${JSON.stringify({ light, dark }, null, 2)} as const;
export const firmExample = ${JSON.stringify(firm, null, 2)} as const;
export const font = ${JSON.stringify(t.font, null, 2)} as const;
export const space = ${JSON.stringify(t.space)} as const;
export const motion = ${JSON.stringify(t.motion, null, 2)} as const;
export const layout = ${JSON.stringify(t.layout, null, 2)} as const;
export type ColorToken = keyof typeof color.light;
`;

const outputs = [
  [join(web, "styles", "tokens.css"), tokensCss],
  [join(web, "styles", "type.css"), typeCss],
  [join(web, "lib", "design", "tokens.ts"), tokensTs],
];
if (process.argv.includes("--check")) {
  const stale = outputs.filter(([p, s]) => !existsSync(p) || readFileSync(p, "utf8") !== s).map(([p]) => p);
  if (stale.length) { console.error(`Out of date; run npm run tokens:\n${stale.join("\n")}`); process.exit(1); }
  console.log("tokens up to date");
} else {
  for (const [p, s] of outputs) writeFileSync(p, s);
  console.log(`wrote ${outputs.map(([p]) => p.replace(web + "/", "")).join(", ")}`);
}
